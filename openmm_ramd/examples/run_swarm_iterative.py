"""
Run an iterative Tau-RAMD swarm from starting structures generated by
conventional MD.
"""

import os
import json
import argparse

import numpy as np
import mdtraj

import openmm_ramd.helper as openmm_ramd_helper
import openmm_ramd.analyze.tau_ramd as tau_ramd_analysis

DEFAULT_STEPS_BETWEEN_STRUCTURES = 1250000
INITIAL_NUM_STARTING_STRUCTURES = 5
INITIAL_NUM_TRAJECTORIES = 15
TRAJECTORY_INCREMENT = 5
MAX_NUM_STARTING_STRUCTURES = 8
MAX_RELATIVE_SD = 0.5

def starting_structure_name(replica_index):
    return f"starting_{replica_index}.pdb"

def starting_state_name(replica_index):
    return f"starting_{replica_index}.xml"

def generate_starting_structure(
        ff_parameters,
        sim_parameters,
        ramd_parameters,
        replica_index,
        steps_between_structures,
        cuda_device_index="0",
        ):
    starting_ff_parameters = dict(ff_parameters)
    starting_sim_parameters = dict(sim_parameters)
    random_seed = starting_sim_parameters.get("random_seed", 0)
    if random_seed != 0:
        starting_sim_parameters["random_seed"] = random_seed + replica_index
    
    openmm_ramd_helper.validate_sim_parameters(starting_sim_parameters)
    openmm_ramd_helper.validate_ramd_parameters(ramd_parameters)
    topology, system = openmm_ramd_helper.choose_topology_system_from_params(
        starting_ff_parameters, starting_sim_parameters)
    integrator = openmm_ramd_helper.choose_conventional_integrator(
        starting_sim_parameters)
    platform, properties = openmm_ramd_helper.choose_platform_and_properties(
        cuda_device_index)
    openmm_ramd_helper.add_restraints_to_system(
        system, starting_ff_parameters["pdb_filename"], starting_sim_parameters)
    simulation = openmm_ramd_helper.make_conventional_simulation(
        topology, system, integrator, platform, properties, starting_ff_parameters,
        starting_sim_parameters, minimize=True)
    openmm_ramd_helper.write_conformations_to_pdb(
        simulation, 1, steps_between_structures,
        structure_basename=starting_structure_name(replica_index),
        rec_indices=ramd_parameters.get("receptor_indices", []),
    )
    pdb = openmm_ramd_helper.openmm_app.PDBFile(
        starting_structure_name(replica_index))
    simulation.context.setPositions(pdb.positions)
    state = simulation.context.getState(
        getPositions=True, getVelocities=True, enforcePeriodicBox=True)
    with open(starting_state_name(replica_index), "w") as f:
        f.write(openmm_ramd_helper.openmm.XmlSerializer.serialize(state))

def ensure_starting_structures(
        ff_parameters,
        sim_parameters,
        ramd_parameters,
        num_replicas,
        steps_between_structures,
        cuda_device_index="0",
        ):
    for replica_index in range(num_replicas):
        if os.path.exists(starting_structure_name(replica_index)) \
                and os.path.exists(starting_state_name(replica_index)):
            continue
        print("Generating starting structure", replica_index)
        generate_starting_structure(
            ff_parameters, sim_parameters, ramd_parameters, replica_index,
            steps_between_structures, cuda_device_index=cuda_device_index)

def get_restart_trajectory_count(replica_index, num_velocity_restarts):
    num_logs = 0
    while os.path.exists(f"ramd_{replica_index}_{num_logs}.log"):
        num_logs += 1
    if num_logs <= num_velocity_restarts:
        return num_velocity_restarts
    num_added = num_logs - num_velocity_restarts
    num_batches = (num_added + TRAJECTORY_INCREMENT - 1) // TRAJECTORY_INCREMENT
    return num_velocity_restarts + num_batches * TRAJECTORY_INCREMENT

def get_restart_replica_count(num_starting_structures):
    num_replicas = num_starting_structures
    while (num_replicas < MAX_NUM_STARTING_STRUCTURES
            and os.path.exists(f"ramd_{num_replicas}_0.log")):
        num_replicas += 1
    return num_replicas

def get_ramd_log_files(replica_counts):
    ramd_log_files = []
    for replica_index, num_trajectories in replica_counts.items():
        for trajectory_index in range(num_trajectories):
            ramd_log_filename = f"ramd_{replica_index}_{trajectory_index}.log"
            if os.path.exists(ramd_log_filename):
                ramd_log_files.append(ramd_log_filename)
    return ramd_log_files

def run_ramd_trajectory(
        ff_parameters,
        sim_parameters,
        ramd_parameters,
        replica_index,
        trajectory_index,
        cuda_device_index="0",
        print_completion=True,
        ):
    ramd_log_filename = f"ramd_{replica_index}_{trajectory_index}.log"
    trajectory_filename = None
    if sim_parameters.get("steps_per_trajectory_update") is not None:
        trajectory_filename = f"ramd_trajectory_{replica_index}_{trajectory_index}.dcd"
    if openmm_ramd_helper.should_run(ramd_log_filename):
        positions, box_vectors = openmm_ramd_helper.simulate_ramd(
            ff_parameters=ff_parameters,
            sim_parameters=sim_parameters,
            ramd_parameters=ramd_parameters,
            starting_structure_name=starting_structure_name(replica_index),
            minimize=False,
            ramd_log_filename=ramd_log_filename,
            cuda_device_index=cuda_device_index,
            trajectory_filename=trajectory_filename,
            starting_state_name=starting_state_name(replica_index),
            )
        pdb_filename = ff_parameters["pdb_filename"]
        traj = mdtraj.load(pdb_filename)
        traj.xyz = np.asarray(positions, dtype=np.float32)
        traj.unitcell_vectors = np.asarray(box_vectors, dtype=np.float32)
        receptor_indices = ramd_parameters["receptor_indices"]
        atom_set_list = [set(traj.topology.atom(i) for i in receptor_indices)]
        traj.xyz = traj.xyz.astype(np.float32)
        traj.image_molecules(inplace=True, anchor_molecules=atom_set_list)
        traj.save(f"ramd_frames_{replica_index}_{trajectory_index}.dcd")
        if print_completion:
            print("Completed simulation, now on to simulation", replica_index+1, trajectory_index+1)
    else:
        print(f"Skipping simulation {replica_index} {trajectory_index} with output file "
              f"{ramd_log_filename}. Already completed.")

def relative_sd_exceeded(sd, value):
    return value != 0 and sd / value > MAX_RELATIVE_SD

def run_swarm_iterative(parameter_file, cuda_device_index="0"):
    with open(parameter_file) as f:
        parameters = json.load(f)

    ff_parameters = parameters.get("ff_parameters", {})
    sim_parameters = parameters.get("sim_parameters", {})
    ramd_parameters = parameters.get("ramd_parameters", {})
    num_starting_structures = ramd_parameters.get(
        "num_starting_structures", INITIAL_NUM_STARTING_STRUCTURES)
    steps_between_structures = ramd_parameters.get(
        "steps_between_structures", DEFAULT_STEPS_BETWEEN_STRUCTURES)
    num_velocity_restarts = ramd_parameters.get(
        "num_velocity_restarts", INITIAL_NUM_TRAJECTORIES)
    num_replicas = get_restart_replica_count(num_starting_structures)
    replica_counts = {
        replica_index: get_restart_trajectory_count(
            replica_index, num_velocity_restarts)
        for replica_index in range(num_replicas)
    }
    
    while True:
        ensure_starting_structures(
            ff_parameters, sim_parameters, ramd_parameters, num_replicas,
            steps_between_structures, cuda_device_index=cuda_device_index)
        final_replica_index = max(replica_counts)
        for replica_index, num_trajectories in replica_counts.items():
            for trajectory_index in range(num_trajectories):
                run_ramd_trajectory(
                    ff_parameters, sim_parameters, ramd_parameters,
                    replica_index, trajectory_index,
                    cuda_device_index=cuda_device_index,
                    print_completion=not (
                        replica_index == final_replica_index
                        and trajectory_index == num_trajectories - 1))
        
        ramd_log_files = get_ramd_log_files(replica_counts)
        replica_results, tau_comp, SD_comp, avg_SD_r, SD_replicas \
            = tau_ramd_analysis.tau_ramd_replicas(ramd_log_files)
        tau_ramd_analysis.print_tau_ramd_results(
            replica_results, tau_comp, SD_comp, avg_SD_r, SD_replicas)
        
        added_trajectories = False
        for replica_result in replica_results:
            if relative_sd_exceeded(replica_result["SD_r"], replica_result["t_r"]):
                replica_index = replica_result["replica_index"]
                replica_counts[replica_index] += TRAJECTORY_INCREMENT
                added_trajectories = True
                print(f"Replica {replica_index + 1} SD_r exceeded 50%; "
                      f"increasing trajectories to {replica_counts[replica_index]}.")
        if added_trajectories:
            continue
        
        if relative_sd_exceeded(SD_replicas, tau_comp):
            if num_replicas >= MAX_NUM_STARTING_STRUCTURES:
                print("SD_replicas exceeded 50%, but maximum number of replicas was reached.")
                break
            replica_counts[num_replicas] = num_velocity_restarts
            num_replicas += 1
            print(f"SD_replicas exceeded 50%; adding replica {num_replicas}.")
            continue
        
        break

if __name__ == "__main__":
    argparser = argparse.ArgumentParser(description=__doc__)
    argparser.add_argument(
        "parameter_file", metavar="PARAMETER_FILE", type=str,
        help="The parameter file containing all the input files for a system.")
    argparser.add_argument(
        "-c", "--cuda_device_index", dest="cuda_device_index", default="0",
        help="modify which cuda_device_index to run the simulation on. For "
        "example, the number 0 or 1 would suffice. To run on multiple GPU "
        "indices, simply enter comma separated indices. Example: '0,1'. "
        "If a value is not supplied, '0' will be used by default.", type=str)
    args = vars(argparser.parse_args())
    run_swarm_iterative(args["parameter_file"], args["cuda_device_index"])
